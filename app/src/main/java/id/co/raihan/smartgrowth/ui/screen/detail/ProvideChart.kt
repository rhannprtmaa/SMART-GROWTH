                ChartType.TB_USIA -> provideMaleTbUsia2Year()
                ChartType.LK_USIA -> provideMaleLkUsia()
            }
        }

        Gender.Female -> {
            when (chartType) {
                ChartType.BB_USIA -> provideFemaleBbUsia()
                ChartType.TB_USIA -> provideFemaleTbUsia()
                ChartType.BB_TB -> provideFemaleBbTb()
                ChartType.LK_USIA -> provideFemaleLkUsia()
            }
        }
    }
}

